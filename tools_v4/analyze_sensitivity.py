"""
tools_v4/analyze_sensitivity.py -- per-game view of docs_v4/sensitivity_m2.json.

For every fixture game it lines up:
  * how the observed market moved from open to close, expressed relative to
    the closing favourite (+ = the favourite got more expensive, in points;
    juice-only moves expressed as implied-probability change of the favourite);
  * the Need (favourite / underdog) per seed and mean favourite pressure, under
    the baseline, the behaviour-neutral control, and the market counterfactuals;
  * the exact SHARP vs non-sharp split of favourite pressure.
Appends a section to docs_v4/sensitivity_m2.md.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sportsbook_v4.market import implied_probability  # noqa: E402
from tests_v4 import fixtures as fx  # noqa: E402

DOCS = Path(__file__).resolve().parent.parent / "docs_v4"
WEEKS = {"moving": fx.NFL_WEEK, "static": fx.static_week(), "reversed": fx.reversed_week()}
SHOW = ["baseline", "neutral_behaviour", "sharp_share_0", "mkt_static", "mkt_reversed",
        "neutral_mkt_static", "neutral_mkt_reversed"]


def movement(week, gid):
    path = next(g[6] for g in week if g[0] == gid)
    (_, o_hs, o_hp, o_ap), (_, c_hs, c_hp, c_ap) = path[0], path[-1]
    if c_hs == 0:
        return None, 0.0, 0.0
    fav = "home" if c_hs < 0 else "away"
    pts = (o_hs - c_hs) if fav == "home" else (c_hs - o_hs)          # + : favourite now lays more
    o_price, c_price = (o_hp, c_hp) if fav == "home" else (o_ap, c_ap)
    juice = implied_probability(c_price) - implied_probability(o_price) if pts == 0 else 0.0
    return fav, pts, juice


def main():
    rep = json.loads((DOCS / "sensitivity_m2.json").read_text())["variants"]
    lines = ["", "## Per-game: Need vs observed market movement (generated by tools_v4/analyze_sensitivity.py)", "",
             "Movement is open→close relative to the closing favourite: + points = favourite got more expensive; "
             "juice = implied-probability change of the favourite's price when the number did not move.", ""]
    for market_key in ("moving", "static", "reversed"):
        names = [n for n in SHOW if n in rep and rep[n]["market"] == market_key]
        if not names:
            continue
        lines += [f"### Market path: {market_key}", "",
                  "| Game | Closing fav | Fav move pts | Fav juice Δ | " +
                  " | ".join(f"{n}: dog-Need seeds / mean FP / sharp FP" for n in names) + " |",
                  "|---|---|---|---|" + "---|" * len(names)]
        for gid, *_ in WEEKS[market_key]:
            fav, pts, juice = movement(WEEKS[market_key], gid)
            cells = []
            for n in names:
                rows = [r for r in rep[n]["rows"] if r["game"] == gid and "need_rel" in r]
                if not rows:
                    cells.append("pick'em")
                    continue
                dog = sum(r["need_rel"] == "underdog" for r in rows)
                fp = sum(r["fav_pressure"] for r in rows) / len(rows)
                sfp = sum(r["by_archetype"].get("SHARP", 0.0) for r in rows) / len(rows)
                cells.append(f"{dog}/{len(rows)} / {fp:+.2f} / {sfp:+.2f}")
            lines.append(f"| {gid} | {fav or '—'} | {pts:+.1f} | {juice:+.3f} | " + " | ".join(cells) + " |")
        lines.append("")
    with open(DOCS / "sensitivity_m2.md", "a") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
